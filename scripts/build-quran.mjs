// Copies the Quran text (quran-json, CC BY-SA 4.0 per its LICENSE file: Uthmani text from quranenc.com, English by Saheeh International)
// into public/quran/en.json (fetched when the Quran page opens) and writes the small surah index src/data/surahs.ts.
// Run: node scripts/build-quran.mjs
import { readFileSync, writeFileSync } from "node:fs";
const src = JSON.parse(readFileSync(new URL("../node_modules/quran-json/dist/quran_en.json", import.meta.url)));
// compact form: [surah][ayah] = [arabic, english]
writeFileSync(new URL("../public/quran/en.json", import.meta.url), JSON.stringify(src.map(s => s.verses.map(v => [v.text, v.translation]))));
const idx = src.map(s => [s.transliteration, s.translation, s.name, s.total_verses]);
writeFileSync(new URL("../src/data/surahs.ts", import.meta.url),
  "// Generated by scripts/build-quran.mjs from quran-json. Do not edit by hand.\n" +
  "/** [transliterated name, English meaning, Arabic name, number of ayahs], surah 1 first. */\n" +
  `export const SURAHS: [string, string, string, number][] = ${JSON.stringify(idx)};\n` +
  `export const TOTAL_AYAHS = ${idx.reduce((a, s) => a + s[3], 0)};\n`);
console.log("surahs", idx.length, "ayahs", idx.reduce((a, s) => a + s[3], 0));
